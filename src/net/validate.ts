/**
 * Strict shape check for Commands that arrive over the network. A malformed command would throw
 * inside every client's sim at the same tick, so the relay drops anything that is not exactly a
 * well-formed Command (and clients re-check what they receive). Output is a fresh object with
 * only the known fields, so extra properties never reach the sim.
 */
import { BUILDINGS, ITEM_SLOTS, type BuildingType, type ItemSlot } from '../config/balance';
import { ARMY, HUNTER_SKILLS, type ArmyType, type HunterSkill } from '../config/lategame';
import type { Command } from '../sim/commands';
import type { Order } from '../sim/types';

const MAX_IDS = 64;
const MAX_COORD = 1e5;

type Obj = Record<string, unknown>;

const isObj = (v: unknown): v is Obj => !!v && typeof v === 'object' && !Array.isArray(v);
const num = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v) && Math.abs(v) <= MAX_COORD;
const id = (v: unknown): v is number => typeof v === 'number' && Number.isInteger(v) && v >= 0 && v < 1e9;
const ids = (v: unknown): number[] | null => (Array.isArray(v) && v.length <= MAX_IDS && v.every(id) ? [...v] : null);
const oneOf = <T extends string>(v: unknown, keys: readonly string[]): v is T => typeof v === 'string' && keys.includes(v);

const BUILD_TYPES = Object.keys(BUILDINGS);
const ARMY_TYPES = Object.keys(ARMY);
const SKILLS = Object.keys(HUNTER_SKILLS);

function order(v: unknown): Order | null {
  if (!isObj(v)) return null;
  switch (v.type) {
    case 'move':
    case 'attackMove':
      return num(v.x) && num(v.y) ? { type: v.type, x: v.x, y: v.y } : null;
    case 'attack':
    case 'repair':
      return id(v.targetId) ? { type: v.type, targetId: v.targetId } : null;
    case 'build':
      return oneOf<BuildingType>(v.btype, BUILD_TYPES) && id(v.tx) && id(v.ty) ? { type: 'build', btype: v.btype, tx: v.tx, ty: v.ty } : null;
    default:
      return null;
  }
}

export function sanitizeCommand(v: unknown): Command | null {
  if (!isObj(v)) return null;
  switch (v.t) {
    case 'order': {
      const u = ids(v.unitIds);
      const o = order(v.order);
      return u && o ? { t: 'order', unitIds: u, order: o, queue: v.queue === true } : null;
    }
    case 'stop': {
      const u = ids(v.unitIds);
      return u ? { t: 'stop', unitIds: u } : null;
    }
    case 'upgrade':
    case 'demolish':
    case 'cancel': {
      const b = ids(v.buildingIds);
      return b ? { t: v.t, buildingIds: b } : null;
    }
    case 'buy':
      return oneOf<ItemSlot>(v.slot, ITEM_SLOTS) ? { t: 'buy', slot: v.slot } : null;
    case 'train':
      return id(v.buildingId) && oneOf<ArmyType>(v.utype, ARMY_TYPES) ? { t: 'train', buildingId: v.buildingId, utype: v.utype } : null;
    case 'rally': {
      const b = ids(v.buildingIds);
      return b && num(v.x) && num(v.y) ? { t: 'rally', buildingIds: b, x: v.x, y: v.y } : null;
    }
    case 'skill':
      if (!oneOf<HunterSkill>(v.skill, SKILLS)) return null;
      if (v.targetId !== undefined && !id(v.targetId)) return null;
      return v.targetId === undefined ? { t: 'skill', skill: v.skill } : { t: 'skill', skill: v.skill, targetId: v.targetId };
    // 'leave' is only ever generated by the relay itself, never accepted from a client
    default:
      return null;
  }
}
